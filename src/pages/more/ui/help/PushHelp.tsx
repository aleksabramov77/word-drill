import { Article, Bullets, H2, Note, Steps } from "./parts.tsx";

export function PushHelp() {
  return (
    <Article>
      <p>
        Уведомления приходят, даже когда Word Drill закрыт — и когда его
        смахнули из списка открытых приложений.
      </p>

      <H2>Как уведомление доходит до телефона</H2>
      <Steps>
        <li>
          Раз в минуту сервер Word Drill решает, пора ли тебе слово (правила
          ниже).
        </li>
        <li>
          Сервер не держит связь с телефоном сам — он передаёт уведомление
          службе доставки платформы: на iPhone это Apple, на Android — Google.
          Те же службы доставляют уведомления всем обычным приложениям.
        </li>
        <li>
          Телефон на мгновение будит маленький фоновый обработчик Word Drill
          (service worker), и тот показывает уведомление.
        </li>
        <li>Нажатие на уведомление открывает тренировку именно этого слова.</li>
      </Steps>

      <H2>Когда приходят слова</H2>
      <Bullets>
        <li>Только в твои часы: по умолчанию с 9 до 22 по времени телефона.</li>
        <li>
          Не чаще раза в 20 минут. Если уведомления остаются без ответа, пауза
          удваивается: 20 → 40 → 80 минут… но не больше 4 часов. Ответил — снова
          20.
        </li>
        <li>Не больше 30 уведомлений и 5 новых слов в день.</li>
        <li>
          Приходит слово, которое ты вероятнее всего уже забываешь. Нечего
          повторять — новое слово из твоего списка.
        </li>
        <li>
          Только что добавленное слово приходит не раньше чем через час — сразу
          его можно потренировать в приложении.
        </li>
        <li>
          Новое уведомление заменяет неотвеченное, так что они не копятся.
          Пропущенное уведомление ошибкой не считается.
        </li>
      </Bullets>
      <p>Часы, паузу и лимиты можно поменять: «Ещё» → «Расписание».</p>

      <H2>Если уведомления не приходят</H2>
      <Bullets>
        <li>
          Проверь, что они включены: «Ещё» → «Уведомления» → «Прислать
          тестовое».
        </li>
        <li>
          В настройках телефона уведомления для Word Drill (на Android — для
          Chrome) не должны быть выключены.
        </li>
        <li>Режим «Не беспокоить» или фокусирование их скрывают.</li>
        <li>
          На iPhone приложение должно стоять на экране «Домой»: если иконку
          удалить, подписка пропадёт.
        </li>
        <li>Без интернета уведомление придёт, когда связь появится.</li>
      </Bullets>
      <Note>
        Каждое устройство подписывается отдельно: включи уведомления на каждом
        телефоне, где хочешь их получать.
      </Note>
    </Article>
  );
}
