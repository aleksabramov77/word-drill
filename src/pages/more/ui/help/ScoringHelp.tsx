import { HARD_HINT_SHARE, HOT_STEPS } from "@/shared/lib/srs";
import { Article, Bullets, Ext, H2, Note } from "./parts.tsx";

const GRADES: { answer: string; grade: string }[] = [
  { answer: "Верно и быстро", grade: "Легко" },
  { answer: "Верно", grade: "Хорошо" },
  { answer: "Верно, но медленно или с опечаткой", grade: "Трудно" },
  {
    answer: `С подсказками, открыто до ${Math.round(HARD_HINT_SHARE * 100)}% букв`,
    grade: "Трудно",
  },
  {
    answer: "Больше подсказок, варианты, показ ответа или «Не помню»",
    grade: "Снова",
  },
];

export function ScoringHelp() {
  return (
    <Article>
      <p>
        Когда повторять слово, считает <b>FSRS</b> (Free Spaced Repetition
        Scheduler) — открытый алгоритм интервальных повторений, тот же, что в
        Anki. Он оценивает, как долго ты помнишь каждое слово, и показывает его
        снова как раз тогда, когда вероятность вспомнить падает до 90%.
        Нейросетей и случайных решений нет: всё считается по формулам.
      </p>

      <H2>Оценка ответа</H2>
      <p>Каждый показ превращается в одну из четырёх оценок FSRS:</p>
      <table className="w-full border-collapse text-left">
        <thead>
          <tr className="border-b text-muted-foreground text-xs">
            <th className="py-1 pr-2 font-normal">Ответ</th>
            <th className="py-1 font-normal">Оценка</th>
          </tr>
        </thead>
        <tbody>
          {GRADES.map((g) => (
            <tr key={g.answer} className="border-b last:border-0">
              <td className="py-1.5 pr-2">{g.answer}</td>
              <td className="py-1.5 font-medium">{g.grade}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <H2>Быстро или медленно</H2>
      <p>
        Длинное слово печатать дольше, поэтому сравнивается не общее время, а
        время на букву. Из времени ответа вычитается «реакция» — прочитать и
        вспомнить (сначала 1,5 секунды, потом приложение узнаёт её по твоим
        ответам), остаток делится на число букв и сравнивается с твоей обычной
        скоростью: быстрее 0,8 от неё — «быстро», медленнее 1,6 — «медленно».
        Первые 5 ответов все считаются обычными, ответ дольше минуты —
        медленным.
      </p>

      <H2>Интервалы</H2>
      <Bullets>
        <li>
          <b>Горячий круг</b> — новое или забытое слово:{" "}
          {HOT_STEPS.map((s) => s.replace("m", " мин")).join(" → ")}. «Хорошо»
          двигает на следующий шаг, «Трудно» оставляет на месте, «Снова»
          возвращает в начало.
        </li>
        <li>
          <b>Дальше — дни.</b> После круга FSRS назначает интервал по прочности
          памяти: обычно около 2 дней, потом около 12, потом больше (до года).
          «Легко» растягивает интервал, «Трудно» укорачивает, «Снова» — обратно
          в горячий круг. К интервалу добавляется небольшой разброс, чтобы слова
          не приходили пачкой.
        </li>
      </Bullets>

      <H2>«Знание» слова</H2>
      <p>
        Процент у слова — прочность памяти: сколько дней слово держится в голове
        с вероятностью 90%. 21 день и больше — 100%, слово «выучено». Пока слово
        в горячем круге, процент растёт с каждым шагом: примерно 5% → 8% → 11%.
        Верный ответ на следующий день поднимает его примерно до 50%.
      </p>
      <Bullets>
        <li>
          <b>Новое</b> — ещё не показывалось.
        </li>
        <li>
          <b>Учится</b> — в горячем круге или прочность меньше 21 дня.
        </li>
        <li>
          <b>С ошибками</b> — последний ответ был «Трудно».
        </li>
        <li>
          <b>Выучено</b> — прочность 21 день и больше.
        </li>
      </Bullets>

      <H2>Почитать</H2>
      <Bullets>
        <li>
          <Ext href="https://ru.wikipedia.org/wiki/Интервальные_повторения">
            Интервальные повторения — Википедия
          </Ext>
        </li>
        <li>
          <Ext href="https://en.wikipedia.org/wiki/Spaced_repetition#Algorithms">
            Spaced repetition: алгоритмы, в том числе FSRS — Wikipedia (англ.)
          </Ext>
        </li>
        <li>
          <Ext href="https://github.com/open-spaced-repetition/awesome-fsrs/wiki/ABC-of-FSRS">
            ABC of FSRS — как устроен алгоритм (англ.)
          </Ext>
        </li>
      </Bullets>
      <Note>
        Отдельной статьи про FSRS в Википедии пока нет — он упомянут в статье
        про интервальные повторения.
      </Note>
    </Article>
  );
}
