import { HARD_HINT_SHARE, TEMPLATE_UNTIL } from "@/shared/lib/srs";
import { Article, Bullets, H2, Note, Steps } from "./parts.tsx";

export function TrainingHelp() {
  return (
    <Article>
      <p>
        Карточка показывает слово по-русски — нужно написать его по-английски.
        Если не получается, карточка не сдаётся, а спускается по лесенке
        подсказок: от «вспомнил сам» к «узнал среди вариантов».
      </p>
      <p>
        Крупно — русское слово, которое ты выбрал при добавлении, мелко под ним
        — другие его переводы из словаря курса, каждый раз в новом порядке.
      </p>

      <H2>Лесенка одного показа</H2>
      <Steps>
        <li>
          <b>Ввод.</b> Пока знание слова ниже {Math.round(TEMPLATE_UNTIL * 100)}
          %, ответ вписывается сразу в шаблон: клетки по числу букв, у фраз — с
          промежутками между словами (артикль и «to» в начале не нужны). Слово
          не разрывается между строками, а слишком длинное переносится с серой
          стрелкой «→» — это не дефис. Коснись любой клетки — курсор после
          каждой буквы сам идёт вправо. Выученные слова пишешь в обычном поле,
          без подсказки длины. Верно или с небольшой опечаткой — готово.
        </li>
        <li>
          <b>Подсказки.</b> По нарастающей. В обычном поле сначала только число
          букв, потом шаблон. Дальше «Ещё буква» открывает следующую (сначала
          первые буквы слов) — открытые буквы голубые, а верно вписанные тобой
          буквы подсказка не трогает. Шаблон заполнен целиком, но с ошибками —
          клетки с неверными буквами подчёркиваются красным, исправь их; одна
          неверная буква засчитывается как опечатка. Неполная неверная попытка
          открывает ещё букву. Последнюю неизвестную букву приложение не
          открывает никогда.
        </li>
        <li>
          <b>Варианты.</b> Если открыто больше половины слова, а ответа всё нет
          (или нажата «Варианты»), — выбор из 4 похожих слов.
        </li>
        <li>
          <b>Показ.</b> Не угадал и в вариантах — приложение показывает ответ, и
          его нужно один раз переписать.
        </li>
      </Steps>
      <p>
        Поле ввода сразу в фокусе, а клавиатура не закрывается между карточками:
        после ответа Enter на клавиатуре — «Дальше». Кнопка с динамиком
        произносит слово голосом телефона.
      </p>
      <p>
        «Не помню» сразу переходит к подсказкам. Такой показ засчитывается как
        «не вспомнил», даже если потом слово нашлось по буквам.
      </p>

      <H2>Что прощается при вводе</H2>
      <Bullets>
        <li>Регистр, лишние пробелы и знаки препинания, «ё» и «е».</li>
        <li>Артикли (a, an, the) и «to» перед глаголом.</li>
        <li>Британское и американское написание (colour = color).</li>
        <li>
          Другой верный перевод (например, «a lot» вместо «by far» для
          «гораздо») — не ошибка: «тоже верно, но загадано другое слово», и
          сразу шаблон без открытых букв. Если потом вспомнишь — «Трудно».
        </li>
        <li>
          Опечатки — по длине слова: в 3–4 буквах только промах по соседней
          клавише, в 5–8 буквах одна ошибка, в длинных словах две. Ответ
          засчитывается, но как «с ошибкой».
        </li>
      </Bullets>

      <H2>Горячий круг</H2>
      <p>
        Слово, которое не вспомнилось с первого раза, возвращается через 1 → 5 →
        15 минут и не отпускает, пока не будет набрано без подсказок. Только
        потом интервалы растут до дней и недель.
      </p>
      <Note>
        Подсказки до {Math.round(HARD_HINT_SHARE * 100)}% букв ещё считаются
        «вспомнил с трудом», больше — «не вспомнил». Подробно — в «Баллы и
        знание».
      </Note>
    </Article>
  );
}
