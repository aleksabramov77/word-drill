import { Article, H2, Note, Steps } from "./parts.tsx";

export function InstallHelp() {
  return (
    <Article>
      <p>
        Word Drill — сайт, который ставится на телефон как приложение: своя
        иконка, открывается без адресной строки, присылает уведомления. Магазин
        приложений не нужен.
      </p>

      <H2>iPhone</H2>
      <Steps>
        <li>Открой этот сайт в Safari.</li>
        <li>
          Нажми «Поделиться» (квадрат со стрелкой; в iOS 26 он может быть в меню
          «•••»).
        </li>
        <li>Выбери «На экран „Домой“» и нажми «Добавить».</li>
        <li>
          Открой Word Drill с иконки, войди и включи уведомления: «Ещё» →
          «Уведомления».
        </li>
      </Steps>
      <Note>
        На iPhone уведомления приходят только приложению с экрана «Домой» (iOS
        16.4 и новее). В обычной вкладке Safari их не будет.
      </Note>

      <H2>Android</H2>
      <Steps>
        <li>Открой этот сайт в Chrome.</li>
        <li>Нажми «⋮» справа от адресной строки.</li>
        <li>
          Выбери «Установить и создать ярлык», затем «Установить». В других
          браузерах пункт может называться «Добавить на главный экран».
        </li>
        <li>
          Открой Word Drill с иконки и включи уведомления: «Ещё» →
          «Уведомления».
        </li>
      </Steps>
      <Note>
        На Android уведомления работают и в обычной вкладке, но с иконки
        удобнее. Если телефон спросит разрешение на уведомления — разреши.
      </Note>

      <H2>Компьютер</H2>
      <p>
        Просто открой сайт в браузере — слова и прогресс те же, что на телефоне,
        если войти той же почтой Google.
      </p>
    </Article>
  );
}
